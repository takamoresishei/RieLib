-- Run this LocalScript by itself in Studio Play mode for engine-level integration checks.
local Root = game:GetService("ReplicatedStorage"):WaitForChild("Aurelis")
local Aurelis = require(Root)
local Cleanup = require(Root.Core.Cleanup)
local baseline = Cleanup.Stats.Resources
local App = Aurelis.New()
local Window = App:CreateWindow({ Title = "Aurelis / engine smoke test", Blur = true })
local Page = Window:AddTab({ Title = "Tests", Icon = "code" })
local Section = Page:AddSection({ Title = "Controls", Collapsible = true })
local Toggle = Section:AddToggle({ Title = "Enabled", Default = false, Flag = "enabled" })
local Slider = Section:AddSlider({ Title = "Speed", Min = 0, Max = 100, Default = 16, Flag = "speed" })
local Color = Section:AddColorPicker({ Title = "Accent", Flag = "accent", Alpha = 0.5 })
local Dropdown = Section:AddDropdown({ Title = "Mode", Values = { "Normal", "Fast" }, Default = "Normal" })
local Heartbeat = game:GetService("RunService").Heartbeat
Heartbeat:Wait()
Heartbeat:Wait()
assert(Section.Root.AbsoluteSize.Y > 44, "Section failed to measure content")
assert(App.Flags.enabled == false)
Slider:SetValue(101)
assert(Slider:GetValue() == 100)
Toggle:SetValue(true)
assert(App.Config:Save("Smoke"))
Toggle:SetValue(false)
Color:SetAlpha(1)
assert(App.Config:Load("Smoke"))
assert(Toggle:GetValue() == true and Color:GetAlpha() == 0.5)
Dropdown:Open()
assert(App.Overlay.Active)
Color:Open()
assert(App.Overlay.Active.Owner == Color)
App.Overlay:Close()
local root = Toggle.Root
Window:SetTheme("Light")
assert(Toggle.Root == root)
Window:SetTheme("Eclipse")
Window:Minimize()
assert(not Window.StatusHost.Visible)
Window:Restore()
Window:Hide()
assert(Window.Launcher.Visible)
Window:Show()
App:Destroy()
Heartbeat:Wait()
assert(Cleanup.Stats.Resources == baseline, "Owned resources were retained after destruction")
print("AURELIS: engine smoke checks passed")
