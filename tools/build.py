#!/usr/bin/env python3
"""Deterministic bundler and Roblox ModuleScript model builder. Python stdlib only."""
from __future__ import annotations
import argparse
import hashlib
import json
from pathlib import Path
import re
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'Aurelis'
REQUIRE = re.compile(r'require\((script(?:\.[A-Za-z_]\w*)+)\)')

def modules():
    result = {}
    for path in sorted(SOURCE.rglob('*.lua')):
        relative = path.relative_to(ROOT).with_suffix('')
        name = relative.parent.as_posix() if relative.name == 'init' else relative.as_posix()
        result[name] = path
    return result

def transform(name: str, source: str, names: set[str]) -> str:
    def resolve(match):
        node = name.split('/')
        for segment in match[1].split('.')[1:]:
            if segment == 'Parent':
                if not node:
                    raise ValueError(f'Require escapes project in {name}')
                node.pop()
            else:
                node.append(segment)
        target = '/'.join(node)
        if target not in names:
            raise ValueError(f'{name}: missing module {target}')
        return '__require(' + json.dumps(target) + ')'
    return REQUIRE.sub(resolve, source)

def bundle_loader() -> str:
    files = modules()
    lines = [
        '-- Generated by tools/build.py. Edit Aurelis/ modules, then rebuild.',
        'local __modules, __cache, __loading = {}, {}, {}',
        'local function __require(name)',
        '    if __cache[name] ~= nil then return __cache[name] end',
        '    assert(not __loading[name], "Cyclic module: " .. name)',
        '    assert(__modules[name], "Missing module: " .. name)',
        '    __loading[name] = true',
        '    local ok, result = pcall(__modules[name], __require)',
        '    __loading[name] = nil',
        '    if not ok then error(result, 2) end',
        '    __cache[name] = result',
        '    return result',
        'end',
    ]
    for name, path in files.items():
        source = path.read_text()
        lines.append('__modules[' + json.dumps(name) + '] = function(__require)\n' + transform(name, source, set(files)) + '\nend')
    return '\n'.join(lines) + '\n'

def model_xml() -> str:
    root = ET.Element('roblox', {'version': '4'})
    def instance(parent, class_name, name, source=None):
        item = ET.SubElement(parent, 'Item', {'class': class_name})
        props = ET.SubElement(item, 'Properties')
        ET.SubElement(props, 'string', {'name': 'Name'}).text = name
        if source is not None:
            ET.SubElement(props, 'ProtectedString', {'name': 'Source'}).text = source
        return item
    aurelis = instance(root, 'ModuleScript', 'Aurelis', (SOURCE/'init.lua').read_text())
    folders = {'Aurelis': aurelis}
    for name, path in modules().items():
        if name == 'Aurelis':
            continue
        segments = name.split('/')
        for i in range(1, len(segments)-1):
            folder = '/'.join(segments[:i+1])
            if folder not in folders:
                folders[folder] = instance(folders['/'.join(segments[:i])], 'Folder', segments[i])
        instance(folders['/'.join(segments[:-1])], 'ModuleScript', segments[-1], path.read_text())
    ET.indent(root, space='  ')
    return '<?xml version="1.0" encoding="utf-8"?>\n' + ET.tostring(root, encoding='unicode') + '\n'

def artifacts():
    loader = bundle_loader()
    return {
        'Aurelis.lua': loader + 'return __require("Aurelis")\n',
        'Showcase.lua': loader + 'local app = __require("Aurelis")\nlocal window = __require("Aurelis/Demo/Showcase")(app)\nreturn app, window\n',
        'Aurelis.rbxmx': model_xml(),
    }

def build(check=False):
    generated = artifacts()
    manifest = {name: hashlib.sha256(content.encode()).hexdigest() for name, content in generated.items()}
    generated['manifest.json'] = json.dumps({'version': '1.0.0', 'sha256': manifest}, indent=2) + '\n'
    destination = ROOT/'dist'
    destination.mkdir(exist_ok=True)
    for name, content in generated.items():
        path = destination/name
        if check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f'Stale artifact: {name}; run python tools/build.py')
        else:
            path.write_text(content)
    print(f'{len(modules())} modules; {len(generated)} deterministic distribution files verified' if check else f'Built {len(modules())} modules into dist/')

if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    build(parser.parse_args().check)
